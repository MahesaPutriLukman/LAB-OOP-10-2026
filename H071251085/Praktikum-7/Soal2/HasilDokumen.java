public class HasilDokumen {

    String namaDokumen;
    String namaThread;
    int jumlahKata;
    long durasi;

    public HasilDokumen(String namaDokumen,
                        String namaThread,
                        int jumlahKata,
                        long durasi) {

        this.namaDokumen = namaDokumen;
        this.namaThread = namaThread;
        this.jumlahKata = jumlahKata;
        this.durasi = durasi;
    }
}